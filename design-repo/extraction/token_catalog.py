#!/usr/bin/env python3
"""Derive tokens/llm/token-catalog.json from the real token files (no hand-typed values).
verify_all.py re-derives it and fails on any difference.

    python3 extraction/token_catalog.py [--write]
"""
import json, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CATALOG_VERSION = "1.0.0"


def load(rel):
    return json.loads((ROOT / rel).read_text())


def derive():
    entries = {}

    def add(tid, cat, value, src):
        entries[tid] = {"category": cat, "value": value, "source": src}

    for tid, t in load("tokens/00-foundation/color.json")["tokens"].items():
        add(tid, "color", t["value"], "tokens/00-foundation/color.json")
    ty = load("tokens/00-foundation/typography.json")
    for group, cat in (("fontFamily", "fontFamily"), ("fontSize", "fontSize"), ("fontWeight", "fontWeight"), ("lineHeight", "lineHeight")):
        for tid, t in ty[group].items():
            add(tid, cat, t["value"], "tokens/00-foundation/typography.json")
    for rel, cat in (("spacing", "spacing"), ("radius", "radius"), ("elevation", "elevation"), ("breakpoint", "breakpoint")):
        for tid, t in load(f"tokens/00-foundation/{rel}.json")["tokens"].items():
            add(tid, cat, t["value"], f"tokens/00-foundation/{rel}.json")
    mo = load("tokens/00-foundation/motion.json")
    for tid, t in mo["ease"].items():
        add(tid, "ease", t["value"], "tokens/00-foundation/motion.json")
    for tid, t in mo["duration"].items():
        add(tid, "duration", t["value"], "tokens/00-foundation/motion.json")
    for tid, t in load("tokens/10-semantic/semantic.json")["tokens"].items():
        cat = tid.split(".")[0]  # surface / text / accent / border
        add(tid, cat, entries[t["ref"]]["value"], "tokens/10-semantic/semantic.json")
    for rel in ("tokens/20-component/component.json", "tokens/30-layout/layout.json"):
        for tid, t in load(rel)["tokens"].items():
            v = entries[t["ref"]]["value"] if "ref" in t else t["value"]
            add(tid, "component" if "20-component" in rel else "layout", v, rel)
    cats = {}
    for tid, e in entries.items():
        cats[e["category"]] = cats.get(e["category"], 0) + 1
    return {"$description": "GENERATED by extraction/token_catalog.py from tokens/00-foundation, 10-semantic, 20-component, 30-layout. Do not hand-edit.",
            "version": CATALOG_VERSION, "count": len(entries), "categories": dict(sorted(cats.items())), "tokens": dict(sorted(entries.items()))}


def dump(o):
    return json.dumps(o, indent=2, ensure_ascii=False) + "\n"


if __name__ == "__main__":
    t = dump(derive())
    f = ROOT / "tokens/llm/token-catalog.json"
    if "--write" in sys.argv:
        f.parent.mkdir(parents=True, exist_ok=True)
        f.write_text(t)
        print("wrote tokens/llm/token-catalog.json")
    else:
        ok = f.exists() and f.read_text() == t
        print("catalog in sync" if ok else "catalog OUT OF SYNC")
        sys.exit(0 if ok else 1)
